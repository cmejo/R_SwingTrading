sim_pretax_daily_returns <- function(bundle, cash_series, cb_thresh = 0.12) {
  port_ret <- numeric(n_total)
  peak_equity <- 1.0; cur_equity <- 1.0
  
  for (t in 1:n_total) {
    dd <- (cur_equity - peak_equity) / peak_equity
    is_cb_active <- if (!is.null(cb_thresh)) (dd <= -cb_thresh) else FALSE
    cb_multiplier <- if (is_cb_active) 0.50 else 1.0
    
    is_bull <- macro_bull[t]
    eff_max_pos <- if (is_bull) 3 else 2
    eff_p_long  <- if (is_bull) 0.58 else 0.65
    
    p_ups   <- bundle$prob[t, ]
    rs_vals <- bundle$rs[t, ]
    vols    <- bundle$vol[t, ]
    rets_b  <- bundle$ret_b[t, ]
    val_flg <- bundle$valid[t, ]
    
    qualify <- which(val_flg & p_ups >= eff_p_long & rs_vals > 0)
    top_idx <- integer(0)
    if (length(qualify) > 0) {
      scores <- p_ups[qualify] * (1 + rs_vals[qualify])
      ranked <- qualify[order(-scores)]
      sec_cnts <- list()
      for (cand in ranked) {
        c_sec <- bundle$sectors[cand]
        cnt <- if (is.null(sec_cnts[[c_sec]])) 0 else sec_cnts[[c_sec]]
        if (cnt < 3) {
          top_idx <- c(top_idx, cand)
          sec_cnts[[c_sec]] <- cnt + 1
          if (length(top_idx) >= eff_max_pos) break
        }
      }
    }
    
    n_sel <- length(top_idx)
    cash_day_ret <- cash_series[t]
    
    if (n_sel > 0) {
      inv_v <- 1 / vols[top_idx]
      weights <- inv_v / sum(inv_v)
      raw_swing_exp <- min(1.0, n_sel / 3.0)
      swing_exposure <- raw_swing_exp * cb_multiplier
      swing_ret <- sum(weights * rets_b[top_idx])
      port_ret[t] <- swing_exposure * swing_ret + (1 - swing_exposure) * cash_day_ret
    } else {
      port_ret[t] <- cash_day_ret
    }
    cur_equity <- cur_equity * (1 + port_ret[t])
    if (cur_equity > peak_equity) peak_equity <- cur_equity
  }
  port_ret
}

# IRS Tax Accounting Simulation Engine (Annual Settlement with Loss Carryforward)
simulate_after_tax <- function(daily_rets, tax_rate = 0.408, start_cap = 10000) {
  years_vec <- as.numeric(format(eval_dates, "%Y"))
  unique_years <- unique(years_vec)
  
  cap_after_tax <- start_cap
  loss_carryforward <- 0.0
  total_tax_paid <- 0.0
  
  after_tax_curve <- numeric(n_total)
  yearly_records <- list()
  idx_counter <- 1
  
  for (yr in unique_years) {
    yr_mask <- which(years_vec == yr)
    yr_rets <- daily_rets[yr_mask]
    yr_cap_start <- cap_after_tax
    
    yr_cumprod <- cumprod(1 + yr_rets)
    for (step_i in seq_along(yr_rets)) {
      after_tax_curve[idx_counter] <- yr_cap_start * yr_cumprod[step_i]
      idx_counter <- idx_counter + 1
    }
    
    yr_cap_end_pre_tax <- yr_cap_start * prod(1 + yr_rets)
    net_gain <- yr_cap_end_pre_tax - yr_cap_start
    
    tax_liability <- 0.0
    taxable_gain  <- 0.0
    if (net_gain > 0) {
      taxable_gain <- max(0, net_gain - loss_carryforward)
      loss_carryforward <- max(0, loss_carryforward - net_gain)
      tax_liability <- taxable_gain * tax_rate
      total_tax_paid <- total_tax_paid + tax_liability
      cap_after_tax <- yr_cap_end_pre_tax - tax_liability
    } else {
      loss_carryforward <- loss_carryforward + abs(net_gain)
      cap_after_tax <- yr_cap_end_pre_tax
    }
    after_tax_curve[idx_counter - 1] <- cap_after_tax
    
    yearly_records[[as.character(yr)]] <- data.frame(
      Year              = yr,
      Start_Capital     = yr_cap_start,
      Gross_End_Capital = yr_cap_end_pre_tax,
      Net_Gain          = net_gain,
      Gross_Return_Pct  = (prod(1 + yr_rets) - 1) * 100,
      Loss_Offset_Used  = min(max(0, net_gain), loss_carryforward + net_gain) - taxable_gain,
      Taxable_Gain      = taxable_gain,
      Tax_Paid          = tax_liability,
      Ending_Capital    = cap_after_tax,
      Loss_Carryforward = loss_carryforward,
      Net_Return_Pct    = (cap_after_tax / yr_cap_start - 1) * 100,
      stringsAsFactors  = FALSE
    )
  }
  
  daily_after_tax_ret <- numeric(n_total)
  daily_after_tax_ret[1] <- (after_tax_curve[1] / start_cap) - 1
  daily_after_tax_ret[2:n_total] <- (after_tax_curve[2:n_total] / after_tax_curve[1:(n_total - 1)]) - 1
  
  eq <- after_tax_curve / start_cap
  cagr <- tail(eq, 1)^(252 / n_total) - 1
  mdd <- min((eq - cummax(eq)) / cummax(eq))
  ann_vol <- sd(daily_after_tax_ret) * sqrt(252)
  sharpe <- (mean(daily_after_tax_ret) * 252 - 0.04) / ann_vol
  downside_ret <- pmin(0, daily_after_tax_ret)
  sortino <- (mean(daily_after_tax_ret) * 252 - 0.04) / (sqrt(mean(downside_ret^2)) * sqrt(252))
  calmar <- cagr / abs(mdd)
  
  list(
    Final_Wealth    = cap_after_tax,
    CAGR            = cagr,
    MaxDD           = mdd,
    Sharpe          = sharpe,
    Sortino         = sortino,
    AnnVol          = ann_vol,
    Calmar          = calmar,
    Total_Tax_Paid  = total_tax_paid,
    Equity_Curve    = after_tax_curve,
    Daily_Rets      = daily_after_tax_ret,
    Yearly_Table    = do.call(rbind, yearly_records)
  )
}

